param([switch]$Check)

$ErrorActionPreference = 'Stop'
$taskRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$outputDir = Join-Path $taskRoot 'docs/generated'
$excludedSegments = @(
    '.git', 'node_modules', '.venv', 'venv', 'env', '.pytest_cache',
    '.mypy_cache', '__pycache__', '.expo', '.expo-shared', 'dist', 'build',
    'web-build', 'coverage', 'htmlcov', '.idea'
)
$generatedPaths = @('docs/generated/FILE_INVENTORY.md', 'docs/generated/DECISION_INDEX.md')

# Prune before traversal: recursive enumeration followed by filtering still
# visits every dependency/cache file. Never follow directory junctions/symlinks.
function Get-InventoryPaths([string]$Directory) {
    foreach ($entry in Get-ChildItem -LiteralPath $Directory -Force) {
        if ($entry.PSIsContainer) {
            if ($entry.Name -notin $excludedSegments -and
                -not ($entry.Attributes -band [System.IO.FileAttributes]::ReparsePoint)) {
                Get-InventoryPaths $entry.FullName
            }
        } else {
            $relative = [System.IO.Path]::GetRelativePath($taskRoot, $entry.FullName).Replace('\', '/')
            if ($relative -notin $generatedPaths -and
                $entry.Name -notlike '*.pyc' -and $entry.Name -notlike '*.tsbuildinfo' -and
                $entry.Name -ne '.coverage') {
                $relative
            }
        }
    }
}

function Write-GeneratedFile([string]$Name, [string[]]$Lines) {
    $path = Join-Path $outputDir $Name
    $content = ($Lines -join "`n") + "`n"
    if ($Check) {
        if (-not (Test-Path -LiteralPath $path) -or
            [System.IO.File]::ReadAllText($path).Replace("`r`n", "`n") -cne $content) {
            throw "Generated index is stale: $path. Run ./scripts/generate_repo_inventory.ps1"
        }
    } else {
        [System.IO.File]::WriteAllText($path, $content, [System.Text.UTF8Encoding]::new($false))
    }
}

if (-not $Check) { New-Item -ItemType Directory -Path $outputDir -Force | Out-Null }
$relativePaths = @(Get-InventoryPaths $taskRoot | Sort-Object)
$inventory = @(
    '# Generated Repository File Inventory', '',
    '> Generated by `scripts/generate_repo_inventory.ps1`. Do not edit by hand.', '',
    'Excludes Git metadata, dependencies, virtual environments, caches, build outputs, and generated indexes.', '',
    '## Files', ''
)
$inventory += $relativePaths | ForEach-Object { '- `' + $_ + '`' }
Write-GeneratedFile 'FILE_INVENTORY.md' $inventory

$decisions = @(
    '# Generated Decision Index', '',
    '> Generated by `scripts/generate_repo_inventory.ps1`. Do not edit by hand.', '',
    'Historical rationale, not an active task list or proof of current implementation.',
    'Search this index, then read only the matching record in [DECISIONS.md](../DECISIONS.md).', ''
)
foreach ($line in Get-Content -LiteralPath (Join-Path $taskRoot 'docs/DECISIONS.md')) {
    if ($line -match '^## (ADR-\d+):\s*(.+)$') {
        $decisions += '- **' + $Matches[1] + '**: ' + $Matches[2]
    }
}
Write-GeneratedFile 'DECISION_INDEX.md' $decisions
if ($Check) { Write-Output 'Generated indexes are current.' }
